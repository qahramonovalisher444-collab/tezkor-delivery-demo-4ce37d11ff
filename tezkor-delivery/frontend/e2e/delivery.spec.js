import { expect, test } from '@playwright/test'
import path from 'node:path'

test.beforeEach(async ({ page }) => {
  await page.route('https://telegram.org/js/telegram-web-app.js*', (route) => route.fulfill({ contentType: 'application/javascript', body: 'window.Telegram={WebApp:{initData:"",ready(){},expand(){},setHeaderColor(){},setBackgroundColor(){},HapticFeedback:{impactOccurred(){}}}}' }))
  await page.route('https://fonts.googleapis.com/**', (route) => route.abort())
  await page.route('https://fonts.gstatic.com/**', (route) => route.abort())
  if (!process.env.TEZKOR_E2E_REAL_TILES) await page.route('https://tile.openstreetmap.org/**', (route) => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256"><rect width="256" height="256" fill="#e8eddf"/><path d="M0 70H256M90 0V256M0 190H256" stroke="#fff" stroke-width="10"/></svg>' }))
})

async function login(page, role) {
  await page.locator('.demo-pill').click()
  await page.getByRole('dialog').getByRole('button', { name: new RegExp(`^${role}`) }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}

async function navigate(page, label) {
  await page.getByRole('button', { name: label, exact: true }).click()
}

async function checkout(page, mobile) {
  if (mobile) await page.locator('.mobile-cart-button').click()
  await page.getByRole('button', { name: 'Buyurtma berish', exact: true }).click()
}

test('customer → admin → courier → customer order lifecycle', async ({ page, context }, testInfo) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await context.grantPermissions(['geolocation'])
  await context.setGeolocation({ latitude: 41.311081, longitude: 69.240562 })
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('heading', { name: 'Bugun nima yeymiz?' })).toBeVisible()
  await page.locator('.product-image-wrap img').evaluateAll((images) => images.forEach((image) => { image.loading = 'eager' }))
  await expect.poll(() => page.locator('.product-image-wrap img').evaluateAll((images) => images.every((image) => image.complete && image.naturalWidth > 0))).toBe(true)
  await page.screenshot({ path: path.resolve(`../../.artifacts/screenshots/${testInfo.project.name}-menu.png`), fullPage: true })
  await page.getByRole('button', { name: 'Klassik burger savatga qo‘shish', exact: true }).click()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(page.getByRole('button', { name: 'Klassik burger sonini kamaytirish', exact: true })).toBeVisible()
  await checkout(page, testInfo.project.name === 'mobile')
  await page.getByRole('dialog').getByRole('button', { name: /^Foydalanuvchi/ }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await checkout(page, testInfo.project.name === 'mobile')
  const address = `E2E ${testInfo.project.name}, Toshkent, Navoiy 12`
  await page.getByRole('dialog').getByLabel('Yetkazish manzili').fill(address)
  await page.getByRole('dialog').getByLabel('Telefon raqam').fill('+998 90 123 45 67')
  await page.getByRole('dialog').getByRole('button', { name: 'Joylashuvim', exact: true }).click()
  await expect(page.getByRole('dialog').locator('.map-coordinate')).toContainText('41.311081, 69.240562')
  const createdOrderResponse = page.waitForResponse((response) => response.url().endsWith('/api/orders/') && response.request().method() === 'POST')
  await page.getByRole('button', { name: /^Tasdiqlash ·/ }).click()
  const savedPoint = await (await createdOrderResponse).json()
  expect(savedPoint.delivery_latitude).toBe('41.311081')
  expect(savedPoint.delivery_longitude).toBe('69.240562')
  const customerOrder = page.locator('.order-card').filter({ hasText: address })
  await expect(customerOrder).toBeVisible()
  const heading = await customerOrder.locator('.order-top strong').textContent()
  const orderNumber = heading.match(/#\d+/)[0]
  await expect(customerOrder.locator('.status-tag')).toHaveText('Yangi')
  await customerOrder.getByRole('button', { name: 'Xaritada ko‘rish', exact: true }).click()
  await expect(customerOrder.getByRole('link', { name: 'OpenStreetMap’da manzilni ochish', exact: true })).toHaveAttribute('href', /mlat=41.311081/)
  await login(page, 'Admin')
  await navigate(page, 'Buyurtmalar')
  await page.getByRole('textbox', { name: 'Buyurtma qidirish' }).fill(orderNumber)
  const adminOrder = page.locator('.order-card').filter({ hasText: address })
  await adminOrder.getByRole('button', { name: 'Tasdiqlash', exact: true }).click()
  await expect(adminOrder.locator('.status-tag')).toHaveText('Tasdiqlangan')
  await adminOrder.getByRole('button', { name: 'Tayyorlashni boshlash', exact: true }).click()
  await expect(adminOrder.locator('.status-tag')).toHaveText('Tayyorlanmoqda')
  await adminOrder.getByRole('button', { name: 'Tayyor deb belgilash', exact: true }).click()
  await expect(adminOrder.locator('.status-tag')).toHaveText('Tayyor')
  await adminOrder.getByRole('combobox').selectOption({ label: 'Sardor Aliyev' })
  await expect(adminOrder.getByRole('button', { name: 'Yetkazishni boshlash', exact: true })).toBeEnabled()
  await login(page, 'Kuryer')
  await page.getByRole('textbox', { name: 'Buyurtma qidirish' }).fill(orderNumber)
  const courierOrder = page.locator('.order-card').filter({ hasText: address })
  await courierOrder.getByRole('button', { name: 'Xaritada ko‘rish', exact: true }).click()
  await expect(courierOrder.locator('.map-coordinate')).toContainText('41.311081, 69.240562')
  await context.grantPermissions(['geolocation'])
  await context.setGeolocation({ latitude: 41.32, longitude: 69.25 })
  await courierOrder.getByRole('button', { name: 'Joylashuvim', exact: true }).click()
  await expect(courierOrder.getByRole('link', { name: 'OpenStreetMap’da yo‘nalishni ochish', exact: true })).toHaveAttribute('href', /route=41.32%2C69.25%3B41.311081%2C69.240562/)
  await courierOrder.getByRole('button', { name: 'Yetkazishni boshlash', exact: true }).click()
  await expect(courierOrder.locator('.status-tag')).toHaveText('Yo‘lda')
  await courierOrder.getByRole('button', { name: 'Yetkazildi', exact: true }).click()
  await expect(courierOrder.locator('.status-tag')).toHaveText('Yetkazildi')
  await login(page, 'Foydalanuvchi')
  await navigate(page, 'Buyurtmalarim')
  await page.getByRole('textbox', { name: 'Buyurtma qidirish' }).fill(orderNumber)
  await expect(page.locator('.order-card').filter({ hasText: address }).locator('.status-tag')).toHaveText('Yetkazildi')
  await navigate(page, 'Mening profilim')
  await expect(page.locator('.profile-editor').getByLabel('Telefon raqam')).toHaveValue('+998901234567')
  await expect(page.locator('.profile-editor').getByLabel('Yetkazish manzili')).toHaveValue(address)
  await page.locator('.profile-editor').getByLabel('Ism', { exact: true }).fill('E2E Aziz')
  await page.getByRole('button', { name: 'Ma’lumotlarni saqlash', exact: true }).click()
  await expect(page.locator('.profile-card h2')).toContainText('E2E Aziz')
  expect(errors).toEqual([])
})

test('map selection clears on address changes and handles denied GPS', async ({ page }, testInfo) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await login(page, 'Foydalanuvchi')
  await page.getByRole('button', { name: 'Klassik burger savatga qo‘shish', exact: true }).click()
  await checkout(page, testInfo.project.name === 'mobile')
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Yetkazish manzili', { exact: true }).fill('Toshkent, Xarita 12')
  await dialog.getByRole('button', { name: 'Markazdagi nuqtani tanlash', exact: true }).click()
  await expect(dialog.locator('.delivery-pin')).toHaveCount(1)
  await dialog.getByLabel('Yetkazish manzili', { exact: true }).fill('Toshkent, Yangi manzil 14')
  await expect(dialog.locator('.delivery-pin')).toHaveCount(0)
  await dialog.getByRole('region', { name: 'Yetkazish nuqtasi xaritasi' }).click({ position: { x: 130, y: 130 } })
  await expect(dialog.locator('.delivery-pin')).toHaveCount(1)
  await expect(dialog.getByRole('link', { name: 'OpenStreetMap', exact: true })).toBeVisible()
  if (process.env.TEZKOR_E2E_REAL_TILES) {
    await expect(dialog.locator('img.leaflet-tile-loaded').first()).toBeVisible()
    await page.screenshot({ path: path.resolve(`../../.artifacts/screenshots/${testInfo.project.name}-checkout-map.png`), fullPage: false })
  }
  await dialog.getByRole('button', { name: 'Xarita nuqtasini olib tashlash', exact: true }).click()
  await expect(dialog.locator('.delivery-pin')).toHaveCount(0)
  await page.evaluate(() => Object.defineProperty(navigator, 'geolocation', { configurable: true, value: { getCurrentPosition(_success, fail) { fail({ code: 1 }) } } }))
  await dialog.getByRole('button', { name: 'Joylashuvim', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Joylashuvga ruxsat berilmadi')
  await expect(dialog.getByLabel('Yetkazish manzili', { exact: true })).toHaveValue('Toshkent, Yangi manzil 14')
  expect(errors).toEqual([])
})

test('admin categories, products, team and notifications work', async ({ page }, testInfo) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await login(page, 'Admin')
  await navigate(page, 'Kategoriyalar')
  const categoryName = `E2E ${testInfo.project.name}`
  await page.getByLabel('Kategoriya nomi').fill(categoryName)
  await page.getByLabel('Menyudagi tartib').fill('99')
  await page.getByRole('button', { name: 'Kategoriya qo‘shish', exact: true }).click()
  await expect(page.getByRole('heading', { name: categoryName, exact: true })).toBeVisible()
  await page.getByRole('button', { name: `${categoryName} tahrirlash`, exact: true }).click()
  await page.getByLabel('Kategoriya nomi').fill(`${categoryName} edited`)
  await page.getByRole('button', { name: 'O‘zgarishlarni saqlash', exact: true }).click()
  await expect(page.getByRole('heading', { name: `${categoryName} edited`, exact: true })).toBeVisible()
  await page.getByRole('button', { name: `${categoryName} edited o‘chirish`, exact: true }).click()
  await page.getByRole('button', { name: 'Ha, o‘chirish', exact: true }).click()
  await expect(page.getByRole('heading', { name: `${categoryName} edited`, exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Burgerlar o‘chirish', exact: true })).toBeDisabled()
  await navigate(page, 'Mahsulotlar')
  await page.getByRole('button', { name: 'Mahsulot qo‘shish', exact: true }).click()
  const productName = `E2E burger ${testInfo.project.name}`
  await page.getByRole('dialog').getByLabel('Mahsulot nomi').fill(productName)
  await page.getByRole('dialog').getByLabel('Narxi (so‘m)').fill('42000')
  await page.getByRole('dialog').getByLabel('Tavsif').fill('Brauzer sinovi uchun mahsulot')
  if (testInfo.project.name === 'mobile') await page.screenshot({ path: path.resolve('../../.artifacts/screenshots/mobile-product-form.png'), fullPage: false })
  await page.getByRole('dialog').getByRole('button', { name: 'Saqlash', exact: true }).click()
  const productRow = page.getByRole('row').filter({ hasText: productName })
  await expect(productRow).toBeVisible()
  await productRow.getByRole('button', { name: 'Tahrirlash', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Sotuvda mavjud').uncheck()
  await page.getByRole('dialog').getByRole('button', { name: 'Saqlash', exact: true }).click()
  await expect(productRow).toContainText('Mavjud emas')
  await navigate(page, 'Foydalanuvchilar')
  const sample = page.getByRole('row').filter({ hasText: 'Sinov mijoz' })
  await sample.getByRole('button', { name: 'Bloklash', exact: true }).click()
  await expect(sample).toContainText('Bloklangan')
  await sample.getByRole('button', { name: 'Faollashtirish', exact: true }).click()
  await expect(sample.locator('.status-tag')).toHaveText('Faol')
  await sample.getByRole('combobox').selectOption('courier')
  await expect(sample.getByRole('combobox')).toHaveValue('courier')
  await sample.getByRole('combobox').selectOption('customer')
  await expect(sample.getByRole('combobox')).toHaveValue('customer')
  await navigate(page, 'Xabarlar')
  await expect(page.getByRole('heading', { name: 'Telegram xabarlari', exact: true })).toBeVisible()
  await expect(page.getByText('Hozircha xabarnoma yo‘q.', { exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
